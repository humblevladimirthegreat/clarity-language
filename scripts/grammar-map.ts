/**
 * Grammar map: which grammar page owns which topic, generated from the sidebar
 * (`reading-order.ts`) and each page's H3 headings.
 *
 *   npm run grammar-map                 print the AGENTS.md block (dry run)
 *   npm run grammar-map -- --headings   print the page + H3 map instead
 *   npm run grammar-map -- --write      write both: AGENTS.md between its markers, and docs/meta/grammar-map.md
 *   npm run grammar-map -- --check      exit 1 when either is stale
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { REPO_ROOT } from "../src/repo-paths.js";
import {
  advancedLessons,
  beginnerLessons,
  intermediateLessons,
  lessonPages,
  levelReviews,
  orientation,
  pageRelPath,
} from "../docs/grammar/.vitepress/lib/reading-order.js";

const GRAMMAR = join(REPO_ROOT, "docs", "grammar");
const AGENTS = join(REPO_ROOT, "AGENTS.md");
const MAP = join(REPO_ROOT, "docs", "meta", "grammar-map.md");
const BEGIN = "<!-- grammar-map: generated by `npm run grammar-map -- --write`; do not edit by hand -->";
const END = "<!-- /grammar-map -->";

type Page = { file: string; rel: string; title: string };

const bands: { name: string; dir: string; pages: Page[] }[] = [
  { name: "Orientation", dir: "", pages: lessonPages(orientation).map(toPage) },
  { name: "Beginner", dir: "beginner/", pages: lessonPages([...beginnerLessons, levelReviews[0]]).map(toPage) },
  { name: "Intermediate", dir: "intermediate/", pages: lessonPages([...intermediateLessons, levelReviews[1]]).map(toPage) },
  { name: "Advanced", dir: "advanced/", pages: lessonPages([...advancedLessons, levelReviews[2]]).map(toPage) },
  { name: "Other pages", dir: "", pages: otherPages() },
];

function toPage({ page, title }: { page: string; title: string }): Page {
  return { file: page, rel: pageRelPath(page), title };
}

/** Top-level pages outside the sidebar groups (recipes, tools, terminology), titled by their H1. */
function otherPages(): Page[] {
  const inGroups = new Set(
    lessonPages([...orientation, ...beginnerLessons, ...intermediateLessons, ...advancedLessons, ...levelReviews]).map((p) => p.page),
  );
  return readdirSync(GRAMMAR)
    .filter((f) => f.endsWith(".md") && !inGroups.has(f))
    .sort()
    .map((f) => ({ file: f, rel: f, title: h1(readFileSync(join(GRAMMAR, f), "utf8")) ?? f }));
}

function h1(markdown: string): string | undefined {
  const m = /^# (.+)$/m.exec(markdown);
  return m ? clean(m[1]!) : undefined;
}

/** Heading text without `{#id}`, bold or link syntax. */
function clean(heading: string): string {
  return heading
    .replace(/\s*\{#[^}]*\}\s*$/, "")
    .replace(/\*\*/g, "")
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
    .trim();
}

/** Taught H3s outside code fences, without the band checkpoints. */
function h3s(markdown: string): string[] {
  const out: string[] = [];
  let fence = false;
  for (const line of markdown.split("\n")) {
    if (/^\s*(```|~~~)/.test(line)) fence = !fence;
    if (fence) continue;
    const m = /^### (.+)$/.exec(line);
    if (m && !/^Practice\b/i.test(clean(m[1]!))) out.push(clean(m[1]!));
  }
  return out;
}

/** Words of a filename, to drop a title that only repeats it. */
function words(s: string): string {
  return s.toLowerCase().replace(/\.md$/, "").replace(/[^a-z0-9]+/g, " ").trim();
}

function entry(p: Page): string {
  const fileWords = words(p.file).split(" ");
  const repeats = words(p.title).split(" ").every((w) => fileWords.includes(w));
  return repeats ? `\`${p.file}\`` : `\`${p.file}\` ${p.title}`;
}

function agentsBlock(): string {
  const lines = [
    BEGIN,
    "",
    "Each grammar page in `docs/grammar/`, by sidebar group in path order, with its title where the filename does not already say it. Sittings live in the group's folder. Taught sections per page: [`docs/meta/grammar-map.md`](docs/meta/grammar-map.md).",
    "",
  ];
  for (const band of bands) {
    if (band.pages.length === 0) continue;
    const where = band.dir ? ` (\`${band.dir}\`)` : "";
    lines.push(`- **${band.name}**${where}: ${band.pages.map(entry).join(" · ")}`);
  }
  lines.push("", END);
  return lines.join("\n");
}

function headingMap(): string {
  const lines = [
    "# Grammar map",
    "",
    "<!-- retie: skip -->",
    "",
    "Editors only. Generated by `npm run grammar-map -- --write` from the sidebar and each page's H3 headings; do not edit by hand. Each grammar page in path order, with the sections it teaches (checkpoints left out).",
  ];
  for (const band of bands) {
    if (band.pages.length === 0) continue;
    lines.push("", `## ${band.name}`, "");
    for (const p of band.pages) {
      const path = join(GRAMMAR, p.rel);
      const sections = existsSync(path) ? h3s(readFileSync(path, "utf8")) : [];
      const head = `\`${p.rel}\` ${p.title}`;
      lines.push(sections.length ? `- ${head}: ${sections.join("; ")}` : `- ${head}`);
    }
  }
  return lines.join("\n") + "\n";
}

function withBlock(agents: string, block: string): string | undefined {
  const start = agents.indexOf(BEGIN);
  const end = agents.indexOf(END);
  if (start < 0 || end < start) return undefined;
  return agents.slice(0, start) + block + agents.slice(end + END.length);
}

const args = new Set(process.argv.slice(2));
const unknown = [...args].filter((a) => !["--write", "--check", "--headings"].includes(a));
if (unknown.length) {
  console.error(`unknown flag(s): ${unknown.join(", ")}`);
  process.exit(2);
}

const block = agentsBlock();
const map = headingMap();

if (args.has("--write") || args.has("--check")) {
  const agents = readFileSync(AGENTS, "utf8");
  const nextAgents = withBlock(agents, block);
  const stale: string[] = [];
  if (nextAgents === undefined) {
    console.warn(`AGENTS.md has no grammar-map markers; add ${BEGIN} … ${END} where the block belongs.`);
  } else if (nextAgents !== agents) {
    stale.push("AGENTS.md");
    if (args.has("--write")) writeFileSync(AGENTS, nextAgents);
  }
  const oldMap = existsSync(MAP) ? readFileSync(MAP, "utf8") : "";
  if (oldMap !== map) {
    stale.push("docs/meta/grammar-map.md");
    if (args.has("--write")) writeFileSync(MAP, map);
  }
  if (args.has("--check") && stale.length) {
    console.error(`grammar map stale: ${stale.join(", ")}. Run npm run grammar-map -- --write.`);
    process.exit(1);
  }
  if (args.has("--write")) console.log(stale.length ? `wrote ${stale.join(", ")}` : "grammar map up to date");
} else {
  console.log(args.has("--headings") ? map : block);
  console.error(`(${Buffer.byteLength(args.has("--headings") ? map : block)} bytes)`);
}
